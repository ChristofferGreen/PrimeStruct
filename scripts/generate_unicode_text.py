#!/usr/bin/env python3
"""Generate stdlib/std/text/unicode_norm_data.prime, the normalization and grapheme tables of /std/text/unicode_norm
(TODO-5634).

Four tables, each a sorted list of fixed-width records in one string literal (hex digits, upper case):
  ccc    8 chars: code point (6), canonical combining class (2), for every code point with a non-zero class.
  decomp 31 chars: code point (6), length (1), four code points (6 each, unused 000000): the full canonical
         decomposition (NFD of the single code point, already in canonical order). Hangul syllables are left out.
  comp   18 chars: first (6), second (6), composite (6): the primary composites, i.e. the pairs that NFC recomposes.
  gcb    13 chars: first (6), last (6), class (1): Grapheme_Cluster_Break ranges. Classes: 1 CR, 2 LF, 3 Control,
         4 Extend, 5 ZWJ, 6 Regional_Indicator, 7 Prepend, 8 SpacingMark, 9 L, A V, B T, E Extended_Pictographic
         (with GCB=Other). Hangul LV/LVT syllables are left out (they are computed) and so is Other.

The decomposition, class and composition data come from Python's `unicodedata`; the grapheme break data comes from
perl's Unicode::UCD (both must be Unicode 15.0). Usage: python3 scripts/generate_unicode_text.py
"""

from __future__ import annotations

import subprocess
import sys
import unicodedata
from pathlib import Path

OUTPUT = Path("stdlib/std/text/unicode_norm_data.prime")
GCB_CODES = {
    "CR": "1", "LF": "2", "Control": "3", "Extend": "4", "ZWJ": "5", "Regional_Indicator": "6", "Prepend": "7",
    "SpacingMark": "8", "L": "9", "V": "A", "T": "B", "ExtPict_XX": "E",
}
SKIPPED_GCB = {"Other", "LV", "LVT"}
HANGUL_FIRST, HANGUL_LAST = 0xAC00, 0xD7A3

PERL = r"""
use Unicode::UCD qw(prop_invmap);
my ($list, $map, $fmt, $def) = prop_invmap("Grapheme_Cluster_Break");
print "version ", Unicode::UCD::UnicodeVersion(), "\n";
for my $i (0 .. $#$list) {
  my $last = $i < $#$list ? $list->[$i + 1] - 1 : 0x10FFFF;
  printf "%X %X %s\n", $list->[$i], $last, $map->[$i];
}
"""


def codepoints():
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        yield cp


def ccc_table() -> str:
    return "".join("%06X%02X" % (cp, unicodedata.combining(chr(cp))) for cp in codepoints() if unicodedata.combining(chr(cp)))


def decomp_table() -> str:
    records = []
    for cp in codepoints():
        if HANGUL_FIRST <= cp <= HANGUL_LAST:
            continue
        decomposed = unicodedata.normalize("NFD", chr(cp))
        if decomposed == chr(cp):
            continue
        points = [ord(c) for c in decomposed]
        assert 1 <= len(points) <= 4, (cp, points)
        records.append("%06X%d%s" % (cp, len(points), "".join("%06X" % p for p in points + [0] * (4 - len(points)))))
    return "".join(records)


def comp_table() -> str:
    pairs = []
    for cp in codepoints():
        if HANGUL_FIRST <= cp <= HANGUL_LAST:
            continue
        decomposition = unicodedata.decomposition(chr(cp))
        if not decomposition or decomposition.startswith("<"):
            continue
        parts = [int(p, 16) for p in decomposition.split()]
        if len(parts) != 2 or unicodedata.normalize("NFC", chr(cp)) != chr(cp):
            continue
        pairs.append((parts[0], parts[1], cp))
    pairs.sort()
    return "".join("%06X%06X%06X" % pair for pair in pairs)


def gcb_table() -> str:
    output = subprocess.run(["perl", "-e", PERL], capture_output=True, text=True, check=True).stdout.splitlines()
    assert output[0] == "version " + unicodedata.unidata_version, (output[0], unicodedata.unidata_version)
    records = []
    for line in output[1:]:
        first, last, name = line.split()
        if name in SKIPPED_GCB:
            continue
        records.append("%06X%06X%s" % (int(first, 16), int(last, 16), GCB_CODES[name]))
    return "".join(records)


def render() -> str:
    tables = (
        ("cccTable", ccc_table(), 8, "canonical combining classes"),
        ("decompTable", decomp_table(), 31, "full canonical decompositions"),
        ("compTable", comp_table(), 18, "primary composites"),
        ("gcbTable", gcb_table(), 13, "grapheme cluster break ranges"),
    )
    lines = [
        "// Generated by scripts/generate_unicode_text.py from Unicode %s. Do not edit." % unicodedata.unidata_version,
        "// Normalization and grapheme tables for /std/text/unicode_norm: sorted fixed-width records, see the generator",
        "// for the formats.",
        "",
        "import /std/text/*",
        "import /std/text/view/*",
        "",
        "namespace std {",
        "  namespace text {",
        "    namespace unicode_norm_data {",
    ]
    for name, data, width, comment in tables:
        assert len(data) % width == 0
        lines += [
            "      // The %s (%d records)." % (comment, len(data) // width),
            "      [public return</std/text/view/StringView>]",
            "      %s() {" % name,
            '        return(textOf("%s"utf8))' % data,
            "      }",
            "",
        ]
    lines += ["    }", "  }", "}", ""]
    return "\n".join(lines)


def main() -> int:
    text = render()
    OUTPUT.write_text(text)
    print("wrote %s (%d bytes)" % (OUTPUT, len(text)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
