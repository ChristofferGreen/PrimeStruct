#!/usr/bin/env python3
"""Generate stdlib/std/text/unicode_data.prime, the case-mapping tables of /std/text/unicode (TODO-5633).

Each table is a sorted list of fixed-width records in one string literal: a 6 digit hex code point, the number of
code points of its mapping (1 to 3) and three 6 digit hex code points (unused ones are 000000). The mappings are the
Unicode default (unconditional) full mappings of Python's `unicodedata` data: `lower`, `upper` and `casefold` of one
code point. Conditional rules (final sigma, Turkish dotted i) are not applied: the operations are locale free.

Usage: python3 scripts/generate_unicode_case.py [--check]
"""

from __future__ import annotations

import argparse
import sys
import unicodedata
from pathlib import Path

OUTPUT = Path("stdlib/std/text/unicode_data.prime")
RECORD_WIDTH = 25


def table(mapping) -> str:
    records = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        original = chr(cp)
        mapped = mapping(original)
        if mapped == original:
            continue
        points = [ord(c) for c in mapped]
        assert 1 <= len(points) <= 3, (cp, points)
        padded = points + [0] * (3 - len(points))
        records.append("%06X%d%s" % (cp, len(points), "".join("%06X" % p for p in padded)))
    text = "".join(records)
    assert len(text) % RECORD_WIDTH == 0
    return text


def render() -> str:
    lower = table(str.lower)
    upper = table(str.upper)
    fold = table(str.casefold)
    lines = [
        "// Generated by scripts/generate_unicode_case.py from Unicode %s. Do not edit." % unicodedata.unidata_version,
        "// Case-mapping tables for /std/text/unicode: sorted records of %d characters" % RECORD_WIDTH,
        "// (code point, mapping length, three mapped code points), see the generator for the format.",
        "",
        "import /std/text/*",
        "import /std/text/view/*",
        "",
        "namespace std {",
        "  namespace text {",
        "    namespace unicode_data {",
    ]
    for name, data, comment in (("lowerTable", lower, "lower case"), ("upperTable", upper, "upper case"), ("foldTable", fold, "case folding")):
        lines += [
            "      // The %s mappings (%d records)." % (comment, len(data) // RECORD_WIDTH),
            "      [public return</std/text/view/StringView>]",
            "      %s() {" % name,
            '        return(textOf("%s"utf8))' % data,
            "      }",
            "",
        ]
    lines += ["    }", "  }", "}", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail when the checked-in file is stale")
    args = parser.parse_args()
    text = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            print("%s is stale: run python3 scripts/generate_unicode_case.py" % OUTPUT)
            return 1
        return 0
    OUTPUT.write_text(text)
    print("wrote %s (%d bytes)" % (OUTPUT, len(text)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
