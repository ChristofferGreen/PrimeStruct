#!/usr/bin/env python3
"""Generates stdlib/std/collections/slice.prime.

`Slice<T, Read>` and `Slice<T, Write>` are the stdlib structs `ReadSlice<T>` and `WriteSlice<T>` (the type
resolver maps the capability argument to the struct name). They share one body of read operations and
differ only in what a narrowed view is and in the write operations the write view adds, so the file is
generated from one template. Run from the repository root:

    python3 scripts/generate_slice_stdlib.py
"""

from pathlib import Path

OUT = Path("stdlib/std/collections/slice.prime")

HEADER = '''// GENERATED by scripts/generate_slice_stdlib.py - edit the generator, not this file.
//
// A borrowed range of contiguous values (docs/spec/strings-and-views.md, Slices): a pointer to the
// first element and a count. It copies nothing. `Slice<T, Read>` names `ReadSlice<T>`, which only
// reads; `Slice<T, Write>` names `WriteSlice<T>`, which also writes (and narrows to write views).
// `readOnly()` turns a write view into a read view. Elements are read and written by value, so `T` is
// a scalar or another `Copy` type. A slice of `u8` steps one byte per element like every `Pointer<u8>`.

import /std/maybe/*
import /std/panic/*
import /std/collections/buffer_unchecked/*

namespace std {
  namespace collections {
  namespace slice {
  // Capability markers: the second argument of `Slice<T, Read>` and `Slice<T, Write>`.
  [public struct]
  Read() {
  }

  [public struct]
  Write() {
  }

  [unsafe return<T>]
  sliceRead<T>([Pointer<T>] base, [i32] index) {
    return(bufferReadUnsafe<T>(base, index))
  }

  [unsafe return<void>]
  sliceWrite<T>([Pointer<T> mut] base, [i32] index, [T move] value) {
    bufferWriteUnsafe<T>(base, index, value)
  }

  [unsafe return<Pointer<T>>]
  sliceOffset<T>([Pointer<T>] base, [i32] index) {
    return(bufferOffsetUnsafe<T>(base, index))
  }

  [return<i32>]
  clampCount([i32] n, [i32] limit) {
    if(n < 0i32) {
      return(0i32)
    }
    if(n > limit) {
      return(limit)
    }
    return(n)
  }

  [return<ReadSlice<T>>]
  readSliceMake<T>([Pointer<T>] data, [i32] count) {
    return(ReadSlice<T>{[data] data, [fieldCount] count})
  }

  [return<WriteSlice<T>>]
  writeSliceMake<T>([Pointer<T>] data, [i32] count) {
    return(WriteSlice<T>{[data] data, [fieldCount] count})
  }

  // ---- operations on a raw range (pointer and count), shared by both views ----

  [unsafe return<i32>]
  rangeFind<T>([Pointer<T>] data, [i32] count, [T] value) {
    for([i32 mut] i{0i32}, i < count, i++) {
      if(sliceRead<T>(data, i) == value) {
        return(i)
      }
    }
    return(-1i32)
  }

  [unsafe return<i32>]
  rangeRfind<T>([Pointer<T>] data, [i32] count, [T] value) {
    for([i32 mut] i{count - 1i32}, i >= 0i32, i--) {
      if(sliceRead<T>(data, i) == value) {
        return(i)
      }
    }
    return(-1i32)
  }

  [unsafe return<i32>]
  rangeOccurrences<T>([Pointer<T>] data, [i32] count, [T] value) {
    [i32 mut] total{0i32}
    for([i32 mut] i{0i32}, i < count, i++) {
      if(sliceRead<T>(data, i) == value) {
        total = total + 1i32
      }
    }
    return(total)
  }

  [unsafe return<bool>]
  rangeEquals<T>([Pointer<T>] data, [i32] count, [Pointer<T>] otherData, [i32] otherCount) {
    if(otherCount != count) {
      return(false)
    }
    for([i32 mut] i{0i32}, i < count, i++) {
      if(sliceRead<T>(data, i) != sliceRead<T>(otherData, i)) {
        return(false)
      }
    }
    return(true)
  }

  // Lexicographic order: -1, 0 or 1.
  [unsafe return<i32>]
  rangeCompare<T>([Pointer<T>] data, [i32] count, [Pointer<T>] otherData, [i32] otherCount) {
    [i32 mut] shared{count}
    if(otherCount < shared) {
      shared = otherCount
    }
    for([i32 mut] i{0i32}, i < shared, i++) {
      [T] mine{sliceRead<T>(data, i)}
      [T] theirs{sliceRead<T>(otherData, i)}
      if(mine < theirs) {
        return(-1i32)
      }
      if(mine > theirs) {
        return(1i32)
      }
    }
    if(count < otherCount) {
      return(-1i32)
    }
    if(count > otherCount) {
      return(1i32)
    }
    return(0i32)
  }

  [unsafe return<bool>]
  rangeStartsWith<T>([Pointer<T>] data, [i32] count, [Pointer<T>] prefixData, [i32] prefixCount) {
    if(prefixCount > count) {
      return(false)
    }
    return(rangeEquals<T>(data, prefixCount, prefixData, prefixCount))
  }

  [unsafe return<bool>]
  rangeEndsWith<T>([Pointer<T>] data, [i32] count, [Pointer<T>] suffixData, [i32] suffixCount) {
    if(suffixCount > count) {
      return(false)
    }
    return(rangeEquals<T>(sliceOffset<T>(data, count - suffixCount), suffixCount, suffixData, suffixCount))
  }

  // Index of the first place the needle occurs, or -1.
  [unsafe return<i32>]
  rangeFindRange<T>([Pointer<T>] data, [i32] count, [Pointer<T>] needleData, [i32] needleCount) {
    if(needleCount > count) {
      return(-1i32)
    }
    [i32] lastStart{count - needleCount}
    for([i32 mut] start{0i32}, start <= lastStart, start++) {
      if(rangeEquals<T>(sliceOffset<T>(data, start), needleCount, needleData, needleCount)) {
        return(start)
      }
    }
    return(-1i32)
  }

  // Where piece `n` (from 0) of the range cut at every element equal to `separator` starts, and ends. An
  // out of range piece is empty and at the end.
  [unsafe return<i32>]
  rangePieceStart<T>([Pointer<T>] data, [i32] count, [T] separator, [i32] n) {
    [i32 mut] pieceStart{0i32}
    [i32 mut] piece{0i32}
    for([i32 mut] i{0i32}, i < count, i++) {
      if(sliceRead<T>(data, i) == separator) {
        if(piece == n) {
          return(pieceStart)
        }
        piece = piece + 1i32
        pieceStart = i + 1i32
      }
    }
    if(piece == n) {
      return(pieceStart)
    }
    return(count)
  }

  [unsafe return<i32>]
  rangePieceEnd<T>([Pointer<T>] data, [i32] count, [T] separator, [i32] n) {
    [i32 mut] piece{0i32}
    for([i32 mut] i{0i32}, i < count, i++) {
      if(sliceRead<T>(data, i) == separator) {
        if(piece == n) {
          return(i)
        }
        piece = piece + 1i32
      }
    }
    return(count)
  }

  [unsafe return<void>]
  rangeFill<T>([Pointer<T> mut] data, [i32] count, [T] value) {
    for([i32 mut] i{0i32}, i < count, i++) {
      sliceWrite<T>(data, i, value)
    }
  }

  [unsafe return<void>]
  rangeSwap<T>([Pointer<T> mut] data, [i32] count, [i32] a, [i32] b) {
    if(a < 0i32 || a >= count || b < 0i32 || b >= count) {
      panic(a)
    }
    [T] held{sliceRead<T>(data, a)}
    sliceWrite<T>(data, a, sliceRead<T>(data, b))
    sliceWrite<T>(data, b, held)
  }

  [unsafe return<void>]
  rangeReverse<T>([Pointer<T> mut] data, [i32] count) {
    [i32 mut] low{0i32}
    [i32 mut] high{count - 1i32}
    while(low < high) {
      rangeSwap<T>(data, count, low, high)
      low = low + 1i32
      high = high - 1i32
    }
  }

  // Copies the source range over the destination (the same count), correct for overlapping ranges.
  [unsafe return<void>]
  rangeCopy<T>([Pointer<T> mut] data, [i32] count, [Pointer<T>] sourceData, [i32] sourceCount) {
    if(sourceCount != count) {
      panic(sourceCount)
    }
    if(sliceOffset<T>(sourceData, 0i32) < sliceOffset<T>(data, 0i32)) {
      for([i32 mut] i{count - 1i32}, i >= 0i32, i--) {
        sliceWrite<T>(data, i, sliceRead<T>(sourceData, i))
      }
    } else {
      for([i32 mut] i{0i32}, i < count, i++) {
        sliceWrite<T>(data, i, sliceRead<T>(sourceData, i))
      }
    }
  }

  // Insertion sort: stable, in place, and small; `T` is ordered.
  [unsafe return<void>]
  rangeSort<T>([Pointer<T> mut] data, [i32] count) {
    for([i32 mut] i{1i32}, i < count, i++) {
      [T] moving{sliceRead<T>(data, i)}
      [i32 mut] j{i - 1i32}
      while(j >= 0i32 && sliceRead<T>(data, j) > moving) {
        sliceWrite<T>(data, j + 1i32, sliceRead<T>(data, j))
        j = j - 1i32
      }
      sliceWrite<T>(data, j + 1i32, moving)
    }
  }
'''

# The read operations, written once. {V} is the view struct, {MAKE} builds a view of the same kind.
READ_METHODS = '''    [return<i32>]
    count() {
      return(this.fieldCount)
    }

    [return<bool>]
    empty() {
      return(this.fieldCount == 0i32)
    }

    [return<T>]
    at([i32] index) {
      if(index < 0i32 || index >= this.fieldCount) {
        panic(index)
      }
      return(sliceRead<T>(this.data, index))
    }

    [return<Maybe<T>>]
    first() {
      if(this.fieldCount == 0i32) {
        return(none<T>())
      }
      return(some<T>(sliceRead<T>(this.data, 0i32)))
    }

    [return<Maybe<T>>]
    last() {
      if(this.fieldCount == 0i32) {
        return(none<T>())
      }
      return(some<T>(sliceRead<T>(this.data, this.fieldCount - 1i32)))
    }

    // Index of the first element equal to `value`, or -1.
    [return<i32>]
    find([T] value) {
      return(rangeFind<T>(this.data, this.fieldCount, value))
    }

    // Index of the last element equal to `value`, or -1.
    [return<i32>]
    rfind([T] value) {
      return(rangeRfind<T>(this.data, this.fieldCount, value))
    }

    [return<bool>]
    contains([T] value) {
      return(rangeFind<T>(this.data, this.fieldCount, value) >= 0i32)
    }

    // How many elements equal `value`.
    [return<i32>]
    occurrences([T] value) {
      return(rangeOccurrences<T>(this.data, this.fieldCount, value))
    }

    // Element-wise equality with another read view.
    [return<bool>]
    equals([ReadSlice<T>] other) {
      return(rangeEquals<T>(this.data, this.fieldCount, other.data, other.fieldCount))
    }

    // Lexicographic order: -1, 0 or 1.
    [return<i32>]
    compare([ReadSlice<T>] other) {
      return(rangeCompare<T>(this.data, this.fieldCount, other.data, other.fieldCount))
    }

    [return<bool>]
    startsWith([ReadSlice<T>] prefix) {
      return(rangeStartsWith<T>(this.data, this.fieldCount, prefix.data, prefix.fieldCount))
    }

    [return<bool>]
    endsWith([ReadSlice<T>] suffix) {
      return(rangeEndsWith<T>(this.data, this.fieldCount, suffix.data, suffix.fieldCount))
    }

    // Index of the first place `needle` occurs, or -1.
    [return<i32>]
    findSlice([ReadSlice<T>] needle) {
      return(rangeFindRange<T>(this.data, this.fieldCount, needle.data, needle.fieldCount))
    }

    // How many pieces `splitPart` has: one more than the separators.
    [return<i32>]
    splitCount([T] separator) {
      return(rangeOccurrences<T>(this.data, this.fieldCount, separator) + 1i32)
    }

    // ---- narrowing: each returns a view of the same elements ----

    [return<{V}<T>>]
    slice([i32] start, [i32] end) {
      if(start < 0i32 || end < start || end > this.fieldCount) {
        panic(start)
      }
      return({MAKE}<T>(sliceOffset<T>(this.data, start), end - start))
    }

    [return<{V}<T>>]
    takeFirst([i32] n) {
      return(this.slice(0i32, clampCount(n, this.fieldCount)))
    }

    [return<{V}<T>>]
    dropFirst([i32] n) {
      return(this.slice(clampCount(n, this.fieldCount), this.fieldCount))
    }

    [return<{V}<T>>]
    takeLast([i32] n) {
      return(this.slice(this.fieldCount - clampCount(n, this.fieldCount), this.fieldCount))
    }

    [return<{V}<T>>]
    dropLast([i32] n) {
      return(this.slice(0i32, this.fieldCount - clampCount(n, this.fieldCount)))
    }

    // The part before `index`.
    [return<{V}<T>>]
    head([i32] index) {
      return(this.slice(0i32, index))
    }

    // The part from `index` on.
    [return<{V}<T>>]
    tail([i32] index) {
      return(this.slice(index, this.fieldCount))
    }

    // The n-th piece (from 0) of the view cut at every element equal to `separator`; an out of range
    // piece is an empty view at the end.
    [return<{V}<T>>]
    splitPart([T] separator, [i32] n) {
      return(this.slice(rangePieceStart<T>(this.data, this.fieldCount, separator, n),
                        rangePieceEnd<T>(this.data, this.fieldCount, separator, n)))
    }
'''

WRITE_METHODS = '''
    // ---- writes ----

    [mut]
    set([i32] index, [T] value) {
      if(index < 0i32 || index >= this.fieldCount) {
        panic(index)
      }
      sliceWrite<T>(this.data, index, value)
    }

    [mut]
    fill([T] value) {
      rangeFill<T>(this.data, this.fieldCount, value)
    }

    [mut]
    swap([i32] a, [i32] b) {
      rangeSwap<T>(this.data, this.fieldCount, a, b)
    }

    [mut]
    reverse() {
      rangeReverse<T>(this.data, this.fieldCount)
    }

    // Copies `other` (the same count) over this view's elements, correct for overlapping ranges.
    [mut]
    copyFrom([ReadSlice<T>] other) {
      rangeCopy<T>(this.data, this.fieldCount, other.data, other.fieldCount)
    }

    [mut]
    sort() {
      rangeSort<T>(this.data, this.fieldCount)
    }

    // The same elements as a read view.
    [return<ReadSlice<T>>]
    readOnly() {
      return(readSliceMake<T>(this.data, this.fieldCount))
    }
'''

STRUCT = '''
  [public struct]
  {V}<T>() {
    [public Pointer<T> mut] data
    [public i32 mut] fieldCount{0i32}

'''

FOOTER = '''  }
  }
  }
}
'''


def main() -> None:
    out = [HEADER]
    out.append(STRUCT.replace("{V}", "ReadSlice"))
    out.append(READ_METHODS.replace("{V}", "ReadSlice").replace("{MAKE}", "readSliceMake"))
    out.append(FOOTER.split("  }\n  }\n  }\n}")[0] + "  }\n")
    out.append(STRUCT.replace("{V}", "WriteSlice"))
    out.append(READ_METHODS.replace("{V}", "WriteSlice").replace("{MAKE}", "writeSliceMake"))
    out.append(WRITE_METHODS)
    out.append(FOOTER)
    OUT.write_text("".join(out))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
