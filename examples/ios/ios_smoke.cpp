  if (!script.valid()) {
    std::cerr << "load failed: " << script.diagnostics() << "\n";
    return 1;
  }
  int32_t hostCalls = 0;
  script.bind("host_add", [&hostCalls](int32_t a, int32_t b) {
    ++hostCalls;
    return a + b;
  });
  const primec::embed::ScriptResult result = script.run();
  if (!result.ok) {
    std::cerr << "run failed: " << result.diagnostics << "\n";
    return 1;
  }
  std::cout << "exit code " << result.exitCode << ", host calls " << hostCalls << "\n";
