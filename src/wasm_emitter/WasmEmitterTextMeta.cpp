// The metadata of the string heap: the allocator of the metadata area, the size class of a block size, the chunk record
// table and the return of chunks to the byte regions (see WasmEmitterTextHeap.cpp for the layout).

// metaAlloc(size i32) -> i32: a zeroed block of the metadata area, `size` rounded up to a power of two (at least 16).
WasmCodeBody buildMetaAlloc(const WasmRuntimeContext &runtime) {
  constexpr uint32_t Size = 0;
  constexpr uint32_t Bucket = 1;
  constexpr uint32_t Rounded = 2;
  constexpr uint32_t Ptr = 3;
  constexpr uint32_t Pages = 4;
  constexpr uint32_t Old = 5;
  constexpr uint32_t Head = 6;
  WasmCodeBody body;
  declareLocals(body, 6, 0);
  WasmAsm a(body.instructions);
  emitBucket(a, Size, Rounded, Bucket);
  bucketHead(a, runtime, Bucket);
  a.localSet(Head);
  a.localGet(Head);
  a.i32Load(0);
  a.localSet(Ptr);
  a.localGet(Ptr);
  a.ifThen();
  a.localGet(Head);
  a.localGet(Ptr);
  a.i32Load(0);
  a.i32Store(0);
  a.localGet(Ptr);
  a.i32Const(0);
  a.localGet(Rounded);
  a.memoryFill();
  a.localGet(Ptr);
  a.ret();
  a.end();
  // carve from the area, taking new pages when it has too little left
  a.globalGet(WasmGlobalTextMetaBump);
  a.localGet(Rounded);
  a.i32Add();
  a.globalGet(WasmGlobalTextMetaEnd);
  a.i32GtU();
  a.ifThen();
  a.localGet(Rounded);
  a.i32Const(65535);
  a.i32Add();
  a.i32Const(16);
  a.i32ShrU();
  a.localSet(Pages);
  a.localGet(Pages);
  a.memoryGrow();
  a.localSet(Old);
  a.localGet(Old);
  a.i32Const(-1);
  a.i32Eq();
  a.ifThen();
  faultOverflow(a, runtime);
  a.end();
  // the shadow stack is no longer the last region of the memory
  a.i32Const(0);
  a.globalSet(WasmGlobalStackLast);
  a.localGet(Old);
  a.i32Const(16);
  a.i32Shl();
  a.globalSet(WasmGlobalTextMetaBump);
  a.globalGet(WasmGlobalTextMetaBump);
  a.localGet(Pages);
  a.i32Const(16);
  a.i32Shl();
  a.i32Add();
  a.globalSet(WasmGlobalTextMetaEnd);
  a.end();
  a.globalGet(WasmGlobalTextMetaBump);
  a.localSet(Ptr);
  a.globalGet(WasmGlobalTextMetaBump);
  a.localGet(Rounded);
  a.i32Add();
  a.globalSet(WasmGlobalTextMetaBump);
  a.localGet(Ptr);
  a.end();
  return body;
}

// metaFree(ptr i32, size i32): returns a block of `metaAlloc(size)` to the list of its size.
WasmCodeBody buildMetaFree(const WasmRuntimeContext &runtime) {
  constexpr uint32_t Ptr = 0;
  constexpr uint32_t Size = 1;
  constexpr uint32_t Bucket = 2;
  constexpr uint32_t Rounded = 3;
  constexpr uint32_t Head = 4;
  WasmCodeBody body;
  declareLocals(body, 3, 0);
  WasmAsm a(body.instructions);
  emitBucket(a, Size, Rounded, Bucket);
  bucketHead(a, runtime, Bucket);
  a.localSet(Head);
  a.localGet(Ptr);
  a.localGet(Head);
  a.i32Load(0);
  a.i32Store(0);
  a.localGet(Head);
  a.localGet(Ptr);
  a.i32Store(0);
  a.end();
  return body;
}

// classIndex(blockBytes i32) -> i32: the number of the size class of a block size (32, 40, 48, 56, 64, 80, 96, 112,
// 128, 160, ...: four sizes per doubling) among the 45 up to 64 KiB.
WasmCodeBody buildClassIndex(const WasmRuntimeContext &) {
  constexpr uint32_t BlockBytes = 0;
  constexpr uint32_t Base = 1;
  constexpr uint32_t Doublings = 2;
  constexpr uint32_t Step = 3;
  WasmCodeBody body;
  declareLocals(body, 3, 0);
  WasmAsm a(body.instructions);
  a.localGet(BlockBytes);
  a.i32Const(64);
  a.i32LeU();
  a.ifThen();
  a.localGet(BlockBytes);
  a.i32Const(32);
  a.i32Sub();
  a.i32Const(3);
  a.i32ShrU();
  a.ret();
  a.end();
  a.i32Const(64);
  a.localSet(Base);
  a.block();
  a.loop();
  a.localGet(Base);
  a.i32Const(1);
  a.i32Shl();
  a.localGet(BlockBytes);
  a.i32GeU();
  a.brIf(1);
  a.localGet(Base);
  a.i32Const(1);
  a.i32Shl();
  a.localSet(Base);
  a.i32Increment(Doublings);
  a.br(0);
  a.end();
  a.end();
  a.localGet(Base);
  a.i32Const(2);
  a.i32ShrU();
  a.localSet(Step);
  // 5 + 4 * doublings + (blockBytes - base) / step - 1
  a.i32Const(4);
  a.localGet(Doublings);
  a.i32Const(2);
  a.i32Shl();
  a.i32Add();
  a.localGet(BlockBytes);
  a.localGet(Base);
  a.i32Sub();
  a.localGet(Step);
  a.i32DivU();
  a.i32Add();
  a.end();
  return body;
}

// blockSizeFor(size i64) -> i64: the VM's `VmTextHeap::blockSizeFor`.
WasmCodeBody buildBlockSizeFor(const WasmRuntimeContext &) {
  constexpr uint32_t Size = 0;
  constexpr uint32_t Base = 1;
  constexpr uint32_t Step = 2;
  constexpr uint32_t Small = 3;
  WasmCodeBody body;
  declareLocals(body, 3, 0);
  WasmAsm a(body.instructions);
  a.localGet(Size);
  a.i64Eqz();
  a.ifThen();
  a.i64Const(0);
  a.ret();
  a.end();
  a.localGet(Size);
  a.i64Const(LargeThreshold);
  a.i64GtU();
  a.ifThen();
  a.localGet(Size);
  a.ret();
  a.end();
  a.localGet(Size);
  a.i32WrapI64();
  a.localSet(Small);
  a.localGet(Small);
  a.i32Const(32);
  a.i32LeU();
  a.ifThen();
  a.i64Const(32);
  a.ret();
  a.end();
  a.i32Const(32);
  a.localSet(Base);
  a.block();
  a.loop();
  a.localGet(Base);
  a.i32Const(1);
  a.i32Shl();
  a.localGet(Small);
  a.i32GeU();
  a.brIf(1);
  a.localGet(Base);
  a.i32Const(1);
  a.i32Shl();
  a.localSet(Base);
  a.br(0);
  a.end();
  a.end();
  a.localGet(Base);
  a.i32Const(2);
  a.i32ShrU();
  a.localSet(Step);
  // base + (size - base + step - 1) / step * step
  a.localGet(Base);
  a.localGet(Small);
  a.localGet(Base);
  a.i32Sub();
  a.localGet(Step);
  a.i32Add();
  a.i32Const(1);
  a.i32Sub();
  a.localGet(Step);
  a.i32DivU();
  a.localGet(Step);
  a.i32Mul();
  a.i32Add();
  a.i64ExtendI32U();
  a.end();
  return body;
}

// find(address i64) -> i32: the large block whose region starts at the offset of the address or the chunk record whose
// region holds it (the VM's `large_.find` and `chunkContaining`, which look at the offset alone), or -1.
WasmCodeBody buildFind(const WasmRuntimeContext &) {
  constexpr uint32_t Address = 0;
  constexpr uint32_t Offset = 1;
  constexpr uint32_t Index = 2;
  constexpr uint32_t Record = 3;
  constexpr uint32_t High = 4;
  constexpr uint32_t BaseOffset = 5;
  constexpr uint32_t Wide = 6;
  WasmCodeBody body;
  declareLocals(body, 5, 1);
  WasmAsm a(body.instructions);
  a.localGet(Address);
  a.i64Const(OffsetMask47);
  a.i64And();
  a.localSet(Wide);
  a.localGet(Wide);
  a.i64Const(32);
  a.i64ShrU();
  a.i64Eqz();
  a.i32Eqz();
  a.ifThen();
  a.i32Const(-1);
  a.ret();
  a.end();
  a.localGet(Wide);
  a.i32WrapI64();
  a.localSet(Offset);
  a.globalGet(WasmGlobalTextRecordHigh);
  a.localSet(High);
  a.block();
  a.loop();
  a.localGet(Index);
  a.localGet(High);
  a.i32GeU();
  a.brIf(1);
  recordAddress(a, Index);
  a.localSet(Record);
  a.localGet(Record);
  a.i32Load(RecKind);
  a.i32Const(1);
  a.i32And();
  a.ifThen();
  recordOffset(a, Record);
  a.localSet(BaseOffset);
  a.localGet(Offset);
  a.localGet(BaseOffset);
  a.i32GeU();
  a.localGet(Offset);
  a.localGet(BaseOffset);
  a.i32Sub();
  a.localGet(Record);
  a.i32Load(RecBytes);
  a.i32LtU();
  a.i32And();
  a.ifThen();
  a.localGet(Index);
  a.ret();
  a.end();
  a.end();
  // a large block is found by the exact offset of its region
  a.localGet(Record);
  a.i32Load(RecKind);
  a.i32Const(2);
  a.i32Eq();
  a.ifThen();
  a.localGet(Offset);
  recordOffset(a, Record);
  a.i32Eq();
  a.ifThen();
  a.localGet(Index);
  a.ret();
  a.end();
  a.end();
  a.i32Increment(Index);
  a.br(0);
  a.end();
  a.end();
  a.i32Const(-1);
  a.end();
  return body;
}

// newRecord() -> i32: the number of an unused chunk record (its fields are zero), growing the table when it is full.
WasmCodeBody buildNewRecord(const WasmRuntimeContext &runtime) {
  constexpr uint32_t Index = 0;
  constexpr uint32_t High = 1;
  constexpr uint32_t Capacity = 2;
  constexpr uint32_t NewCapacity = 3;
  constexpr uint32_t Table = 4;
  WasmCodeBody body;
  declareLocals(body, 5, 0);
  WasmAsm a(body.instructions);
  a.globalGet(WasmGlobalTextRecordHigh);
  a.localSet(High);
  a.block();
  a.loop();
  a.localGet(Index);
  a.localGet(High);
  a.i32GeU();
  a.brIf(1);
  recordAddress(a, Index);
  a.i32Load(RecKind);
  a.i32Eqz();
  a.ifThen();
  a.localGet(Index);
  a.ret();
  a.end();
  a.i32Increment(Index);
  a.br(0);
  a.end();
  a.end();
  a.globalGet(WasmGlobalTextRecordCap);
  a.localSet(Capacity);
  a.localGet(High);
  a.localGet(Capacity);
  a.i32Eq();
  a.ifThen();
  a.localGet(Capacity);
  a.i32Const(1);
  a.i32Shl();
  a.localSet(NewCapacity);
  a.localGet(NewCapacity);
  a.i32Const(6);
  a.i32Shl();
  a.call(textFn(runtime, WasmTextHelper::MetaAlloc));
  a.localSet(Table);
  a.localGet(Table);
  a.globalGet(WasmGlobalTextRecords);
  a.localGet(High);
  a.i32Const(6);
  a.i32Shl();
  a.memoryCopy();
  a.globalGet(WasmGlobalTextRecords);
  a.localGet(Capacity);
  a.i32Const(6);
  a.i32Shl();
  a.call(textFn(runtime, WasmTextHelper::MetaFree));
  a.localGet(Table);
  a.globalSet(WasmGlobalTextRecords);
  a.localGet(NewCapacity);
  a.globalSet(WasmGlobalTextRecordCap);
  a.end();
  a.localGet(High);
  a.i32Const(1);
  a.i32Add();
  a.globalSet(WasmGlobalTextRecordHigh);
  a.localGet(High);
  a.end();
  return body;
}

// rescanLow(blockBytes i32): the lowest chunk (by region offset) of the size class with a free block, recorded in the
// class entry (0 for none): the VM's `withFree.begin()`.
WasmCodeBody buildRescanLow(const WasmRuntimeContext &runtime) {
  constexpr uint32_t BlockBytes = 0;
  constexpr uint32_t Index = 1;
  constexpr uint32_t High = 2;
  constexpr uint32_t Record = 3;
  constexpr uint32_t Best = 4;
  constexpr uint32_t BestOffset = 5;
  constexpr uint32_t Offset = 6;
  WasmCodeBody body;
  declareLocals(body, 6, 0);
  WasmAsm a(body.instructions);
  a.i32Const(-1);
  a.localSet(Best);
  a.globalGet(WasmGlobalTextRecordHigh);
  a.localSet(High);
  a.block();
  a.loop();
  a.localGet(Index);
  a.localGet(High);
  a.i32GeU();
  a.brIf(1);
  recordAddress(a, Index);
  a.localSet(Record);
  a.localGet(Record);
  a.i32Load(RecKind);
  a.i32Const(1);
  a.i32Eq();
  a.localGet(Record);
  a.i32Load(RecBlockBytes);
  a.localGet(BlockBytes);
  a.i32Eq();
  a.i32And();
  a.localGet(Record);
  a.i32Load(RecFreeCount);
  a.i32Const(0);
  a.i32Ne();
  a.i32And();
  a.ifThen();
  recordOffset(a, Record);
  a.localSet(Offset);
  a.localGet(Best);
  a.i32Const(-1);
  a.i32Eq();
  a.localGet(Offset);
  a.localGet(BestOffset);
  a.i32LtU();
  a.i32Or();
  a.ifThen();
  a.localGet(Index);
  a.localSet(Best);
  a.localGet(Offset);
  a.localSet(BestOffset);
  a.end();
  a.end();
  a.i32Increment(Index);
  a.br(0);
  a.end();
  a.end();
  classAddress(a, runtime, BlockBytes);
  a.localGet(Best);
  a.i32Const(1);
  a.i32Add();
  a.i32Store(ClassLow);
  a.end();
  return body;
}

// returnChunk(record i32): gives a chunk's region back (the VM's `returnChunk`): the class holds fewer bytes, the record
// is gone, and the class's lowest chunk with a free block is found again when it was this one.
WasmCodeBody buildReturnChunk(const WasmRuntimeContext &runtime) {
  constexpr uint32_t Record = 0;
  constexpr uint32_t Entry = 1;
  constexpr uint32_t Bytes = 2;
  constexpr uint32_t BlockBytes = 3;
  constexpr uint32_t State = 4;
  constexpr uint32_t Count = 5;
  constexpr uint32_t Class = 6;
  constexpr uint32_t WasLow = 7;
  constexpr uint32_t Base = 8;
  WasmCodeBody body;
  declareLocals(body, 7, 1);
  WasmAsm a(body.instructions);
  recordAddress(a, Record);
  a.localSet(Entry);
  a.localGet(Entry);
  a.i64Load(RecBase);
  a.localSet(Base);
  a.localGet(Entry);
  a.i32Load(RecBytes);
  a.localSet(Bytes);
  a.localGet(Entry);
  a.i32Load(RecBlockBytes);
  a.localSet(BlockBytes);
  a.localGet(Entry);
  a.i32Load(RecBlockCount);
  a.localSet(Count);
  a.localGet(Entry);
  a.i32Load(RecState);
  a.localSet(State);
  classAddress(a, runtime, BlockBytes);
  a.localSet(Class);
  fieldAddLocal(a, Class, ClassHeld, Bytes, true);
  globalAddLocal(a, WasmGlobalTextChunkBytes, Bytes, true);
  a.localGet(Class);
  a.i32Load(ClassLow);
  a.localGet(Record);
  a.i32Const(1);
  a.i32Add();
  a.i32Eq();
  a.localSet(WasLow);
  a.localGet(State);
  a.localGet(Count);
  a.i32Const(2);
  a.i32Shl();
  a.call(textFn(runtime, WasmTextHelper::MetaFree));
  a.localGet(Entry);
  a.i32Const(0);
  a.i32Const(WasmTextRecordBytes);
  a.memoryFill();
  a.localGet(WasLow);
  a.ifThen();
  a.localGet(BlockBytes);
  a.call(textFn(runtime, WasmTextHelper::RescanLow));
  a.end();
  a.localGet(Base);
  a.call(byteFn(runtime, WasmByteHelper::Free));
  a.end();
  return body;
}

// returnFreeChunk(record i32): the VM's `returnFreeChunk`: the class's fully free chunk goes back to the byte regions.
WasmCodeBody buildReturnFreeChunk(const WasmRuntimeContext &runtime) {
  constexpr uint32_t Record = 0;
  constexpr uint32_t Entry = 1;
  constexpr uint32_t Bytes = 2;
  constexpr uint32_t BlockBytes = 3;
  WasmCodeBody body;
  declareLocals(body, 3, 0);
  WasmAsm a(body.instructions);
  recordAddress(a, Record);
  a.localSet(Entry);
  a.localGet(Entry);
  a.i32Load(RecBytes);
  a.localSet(Bytes);
  a.localGet(Entry);
  a.i32Load(RecBlockBytes);
  a.localSet(BlockBytes);
  classAddress(a, runtime, BlockBytes);
  a.i32Const(0);
  a.i32Store(ClassFree);
  globalAddLocal(a, WasmGlobalTextFreeChunkBytes, Bytes, true);
  a.localGet(Record);
  a.call(textFn(runtime, WasmTextHelper::ReturnChunk));
  a.end();
  return body;
}

// largestFreeChunk() -> i32: of the classes' fully free chunks the one with the most bytes (the highest region among
// equals), or -1: the VM's `largestFreeChunk`.
WasmCodeBody buildLargestFreeChunk(const WasmRuntimeContext &runtime) {
  constexpr uint32_t ClassNumber = 0;
  constexpr uint32_t Best = 1;
  constexpr uint32_t BestBytes = 2;
  constexpr uint32_t BestOffset = 3;
  constexpr uint32_t Chunk = 4;
  constexpr uint32_t Entry = 5;
  constexpr uint32_t Bytes = 6;
  constexpr uint32_t Offset = 7;
  WasmCodeBody body;
  declareLocals(body, 8, 0);
  WasmAsm a(body.instructions);
  a.i32Const(-1);
  a.localSet(Best);
  a.block();
  a.loop();
  a.localGet(ClassNumber);
  a.i32Const(static_cast<int32_t>(WasmTextClassCount));
  a.i32GeU();
  a.brIf(1);
  a.localGet(ClassNumber);
  a.i32Const(4);
  a.i32Shl();
  a.i32Const(static_cast<int32_t>(runtime.textClasses));
  a.i32Add();
  a.i32Load(ClassFree);
  a.localSet(Chunk);
  a.localGet(Chunk);
  a.ifThen();
  a.localGet(Chunk);
  a.i32Const(1);
  a.i32Sub();
  a.localSet(Chunk);
  recordAddress(a, Chunk);
  a.localSet(Entry);
  a.localGet(Entry);
  a.i32Load(RecBytes);
  a.localSet(Bytes);
  recordOffset(a, Entry);
  a.localSet(Offset);
  a.localGet(Best);
  a.i32Const(-1);
  a.i32Eq();
  a.localGet(BestBytes);
  a.localGet(Bytes);
  a.i32LtU();
  a.i32Or();
  a.localGet(BestBytes);
  a.localGet(Bytes);
  a.i32Eq();
  a.localGet(BestOffset);
  a.localGet(Offset);
  a.i32LtU();
  a.i32And();
  a.i32Or();
  a.ifThen();
  a.localGet(Chunk);
  a.localSet(Best);
  a.localGet(Bytes);
  a.localSet(BestBytes);
  a.localGet(Offset);
  a.localSet(BestOffset);
  a.end();
  a.end();
  a.i32Increment(ClassNumber);
  a.br(0);
  a.end();
  a.end();
  a.localGet(Best);
  a.end();
  return body;
}

